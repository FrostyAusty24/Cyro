/** Accept only exact historical translations so changing server language cannot orphan receipts. */
export function matchesToolsReference(value: string | undefined, source: string, reference: string): boolean {
  const row = TOOLS_MESSAGE_ROWS.find(candidate => candidate[0] === source);
  return (row ?? [source]).some(template => value === template.replace('{reference}', reference));
}
